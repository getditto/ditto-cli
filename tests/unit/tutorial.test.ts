/** Fake session: canned rows per statement prefix; records every statement. */
function fakeSession(responder: (s: string) => Record<string, unknown>[] | Error = () => []) {
  const executed: string[] = [];
  const session: QueryExecutor = {
    execute: async (s: string) => {
      executed.push(s);
      const r = responder(s);
      if (r instanceof Error) throw r;
      return { items: r.map((value) => ({ value })) } as never;
    },
  };
  return { session, executed };
}

function makeRunner(
  responder?: Parameters<typeof fakeSession>[0],
  opts: { lessons?: Lesson[]; progress?: Progress } = {},
) {
  const { session, executed } = fakeSession(responder);
  const printed: string[] = [];
  const saved: Progress[] = [];
  const runner = new LessonRunner(session, {
    lessons: opts.lessons,
    progress: opts.progress,
    io: { print: (t) => printed.push(t), width: () => 80 },
    saveProgress: (p) => saved.push(p),
  });
  const out = () => printed.join("\n");
  return { runner, executed, printed, saved, out };
}

const products = () => SEED_PRODUCTS.map((p) => ({ ...p }));

describe("LessonRunner", () => {
  it("resets data, prints the banner and first lesson, and shows level badges", async () => {
    const { runner, executed, out } = makeRunner();
    await runner.start();
    expect(executed.slice(0, RESET_STATEMENTS.length)).toEqual(RESET_STATEMENTS);
    expect(out()).toContain("Learn DQL — interactive lessons");
    expect(out()).toContain("Beginner");
    expect(out()).toContain("Lesson 1/");
    expect(out()).toContain("Documents and collections");
    expect(out()).toContain("If you know SQL:");
    expect(out()).toContain("Task:");
  });

  it("resumes from saved progress, or starts at a requested level", async () => {
    const resumed = makeRunner(undefined, { progress: { lesson: 4, completed: [0, 1, 99] } });
    await resumed.runner.start();
    expect(resumed.runner.current).toBe(4);
    expect(resumed.runner.completedCount).toBe(2);
    expect(resumed.out()).toContain("Resuming at lesson 5");

    const adv = makeRunner(undefined, { progress: { lesson: 4, completed: [] } });
    await adv.runner.start({ level: "advanced" });
    expect(adv.runner.current).toBe(firstLessonOf("advanced"));
    expect(adv.out()).not.toContain("Resuming");

    const bad = makeRunner(undefined, { progress: { lesson: 999, completed: [] } });
    expect(bad.runner.current).toBe(0);
  });

  it("passes a correct answer, saves progress, and moves on", async () => {
    const { runner, out, saved } = makeRunner((s) =>
      s.startsWith("SELECT * FROM products") ? products() : [],
    );
    await runner.start();
    expect(await runner.submit("SELECT * FROM products")).toBe(true);
    expect(out()).toContain("✓ Correct!");
    expect(runner.current).toBe(1);
    expect(saved.at(-1)).toEqual({ lesson: 1, completed: [0] });
    expect(out()).toContain("Projection: choosing fields");
  });

  it("explains a wrong answer and stays put", async () => {
    const { runner, out } = makeRunner(() => [{ name: "Green tea" }]);
    await runner.start();
    expect(await runner.submit("SELECT name FROM products WHERE category = 'tea'")).toBe(false);
    expect(out()).toContain("✗ Not quite.");
    expect(runner.current).toBe(0);
  });

  it("reports query errors and checker crashes without advancing", async () => {
    const { runner, out } = makeRunner((s) =>
      s.startsWith("SELEKT") ? new Error("parse error") : [],
    );
    await runner.start();
    expect(await runner.submit("SELEKT 1")).toBe(false);
    expect(out()).toContain("Query error: parse error");

    const crashing: Lesson = {
      ...LESSONS[0]!,
      check: () => {
        throw new Error("boom");
      },
    };
    const c = makeRunner(undefined, { lessons: [crashing] });
    await c.runner.start();
    expect(await c.runner.submit("SELECT 1")).toBe(false);
    expect(c.out()).toContain("Couldn't check that: boom");
  });

  it("renders writes as OK and EXPLAIN / PROFILE with the diagnostic renderers", async () => {
    const { runner, out } = makeRunner((s) => {
      if (s.startsWith("EXPLAIN")) return [{ plan: { "#operator": "indexScan" } }];
      if (s.startsWith("PROFILE"))
        return [
          { name: "x" },
          {
            "~request_profile": {
              times: { elapsed: 1 },
              state: "completed",
              plan: { "#operator": "scan" },
            },
          },
        ];
      return [];
    });
    await runner.start();
    await runner.submit("UPDATE products SET stock = 1 WHERE _id = 'p1'");
    expect(out()).toContain("OK");
    await runner.submit("EXPLAIN SELECT * FROM products");
    expect(out()).toContain("indexScan");
    await runner.submit("PROFILE SELECT * FROM products");
    expect(out()).toContain("Execution Profile");
  });

  it("navigates with next/back/goto/level and lists progress", async () => {
    const { runner, out, printed } = makeRunner();
    await runner.start();
    await runner.back();
    expect(out()).toContain("This is the first lesson.");
    await runner.next();
    expect(runner.current).toBe(1);
    await runner.back();
    expect(runner.current).toBe(0);
    await runner.goto(String(LESSONS.length));
    expect(runner.current).toBe(LESSONS.length - 1);
    await runner.next();
    expect(out()).toContain("This is the last lesson.");
    await runner.goto("0");
    expect(out()).toContain("usage: .goto");
    await runner.level("intermediate");
    expect(runner.current).toBe(firstLessonOf("intermediate"));
    await runner.level("expert");
    expect(out()).toContain("usage: .level beginner|intermediate|advanced");
    printed.length = 0;
    runner.list();
    expect(out()).toContain("Intermediate");
    expect(out()).toContain("← you are here");
    expect(out()).toContain(`0/${LESSONS.length} completed`);
  });

  it("shows hints, answers, and help; reset restores the data", async () => {
    const { runner, out, executed } = makeRunner();
    await runner.start();
    runner.hint();
    expect(out()).toContain("Hint:");
    runner.answer();
    expect(out()).toContain(`${LESSONS[0]!.answer};`);
    executed.length = 0;
    await runner.reset();
    expect(executed.slice(0, RESET_STATEMENTS.length)).toEqual(RESET_STATEMENTS);
    expect(out()).toContain("Practice data restored.");
    expect(LESSON_HELP).toContain(".level <name>");
  });

  it("announces a new level and finishes after the last lesson", async () => {
    const lessons: Lesson[] = [
      { ...LESSONS[0]!, check: () => ({ pass: true }) },
      { ...LESSONS.find((l) => l.level === "advanced" && l.newIn)!, check: () => ({ pass: true }) },
    ];
    const { runner, out } = makeRunner(undefined, { lessons });
    await runner.start();
    await runner.submit("SELECT 1");
    expect(out()).toContain("On to Advanced!");
    expect(out()).toContain("New in SDK 5.2");
    await runner.submit("SELECT 1");
    expect(out()).toContain("You finished all 2 lessons!");

    const partial = makeRunner(undefined, { lessons: [lessons[1]!] });
    await partial.runner.start();
    await partial.runner.goto("1");
    partial.runner.list();
    await partial.runner.submit("SELECT 1");
    expect(partial.out()).toContain("finished all 1 lessons");
  });

  it("highlights code and bold spans", () => {
    expect(highlight("use `SELECT` and **care**")).toBe("use SELECT and care"); // FORCE_COLOR=0
  });
});

describe("lesson checks reject wrong answers with a reason", () => {
  const query = async () => [] as Record<string, unknown>[];
  const ctx = (rows: Record<string, unknown>[], kind = "select", statement = "SELECT 1") => ({
    rows,
    kind: kind as never,
    statement,
    query,
  });

  // "Removing local data" passes when its follow-up query finds no p7 — an empty
  // fake store means it's gone; its failure path is covered below.
  it.each(
    LESSONS.map((l, i) => [i + 1, l.title, l] as const).filter(
      ([, t]) => t !== "Removing local data",
    ),
  )("lesson %i (%s) fails on an empty result", async (_n, _title, lesson) => {
    const r = await lesson.check(ctx([]));
    expect(r.pass).toBe(false);
    if (!r.pass) expect(r.reason.length).toBeGreaterThan(10);
  });

  const byTitle = (t: string) => LESSONS.find((l) => l.title.startsWith(t))!;

  it("asks for identifiable products when names and ids are absent", async () => {
    const r = await byTitle("Filtering").check(ctx([{ price: 1 }]));
    expect(r).toMatchObject({ pass: false, reason: expect.stringContaining("`name`") });
  });

  it("accepts _id instead of name for product sets", async () => {
    const r = await byTitle("Filtering").check(ctx([{ _id: "p1" }, { _id: "p2" }, { _id: "p4" }]));
    expect(r.pass).toBe(true);
  });

  it("checks projections, ordering, groups, and labels precisely", async () => {
    const all = products();
    expect((await byTitle("Projection").check(ctx(all))).pass).toBe(false);
    expect(
      (await byTitle("Sorting").check(ctx([{ name: "Espresso blend" }, { name: "Travel mug" }])))
        .pass,
    ).toBe(false);
    expect((await byTitle("Sorting").check(ctx([{ price: 1 }]))).pass).toBe(false);
    expect(
      (
        await byTitle("Grouping").check(
          ctx([
            { category: "coffee", n: 2 },
            { category: "tea", n: 2 },
            { category: "accessories", n: 1 },
          ]),
        )
      ).pass,
    ).toBe(false);
    expect((await byTitle("Grouping").check(ctx([{ n: 3 }, { n: 2 }, { n: 1 }]))).pass).toBe(false);
    const labels = all.map((p) => ({ name: p.name, a: "in stock" }));
    expect((await byTitle("Conditional").check(ctx(labels))).pass).toBe(false);
    expect((await byTitle("Conditional").check(ctx(all.map(() => ({ a: 1 }))))).pass).toBe(false);
    const espressoOnly = all.map((p) => ({ name: p.name, a: "sold out" }));
    expect((await byTitle("Conditional").check(ctx(espressoOnly))).pass).toBe(false);
  });

  it("checks calculated values and aggregates", async () => {
    const six = (v: number) => SEED_PRODUCTS.map(() => ({ v }));
    expect((await byTitle("Expressions").check(ctx(six(1)))).pass).toBe(false);
    expect((await byTitle("Defaults").check(ctx(six(1)))).pass).toBe(false);
    expect((await byTitle("Defaults").check(ctx([...six(1).slice(1), { v: 13.5 }]))).pass).toBe(
      false,
    );
    expect((await byTitle("Aggregate").check(ctx([{ c: 5 }]))).pass).toBe(false);
    expect((await byTitle("Aggregate").check(ctx([{ c: 6, a: 1 }]))).pass).toBe(false);
    expect((await byTitle("Nested").check(ctx([{ name: "Coffee beans" }]))).pass).toBe(false);
    expect((await byTitle("Filtering groups").check(ctx([{ units: 1 }]))).pass).toBe(false);
    expect((await byTitle("Filtering groups").check(ctx([{ category: "tea" }]))).pass).toBe(false);
  });

  it("checks joins and array predicates", async () => {
    expect((await byTitle("Joining").check(ctx([{ name: "Coffee beans" }]))).pass).toBe(false);
    expect((await byTitle("Joining").check(ctx([{ s: "Andes Roasters" }]))).pass).toBe(false);
    expect(
      (await byTitle("Joining").check(ctx([{ name: "Coffee beans", s: "Andes Roasters" }]))).pass,
    ).toBe(false);
    expect((await byTitle("Conditions on array").check(ctx([{ x: 1 }]))).pass).toBe(false);
    expect(
      (await byTitle("Conditions on array").check(ctx([{ _id: "o1" }, { _id: "o2" }]))).pass,
    ).toBe(false);
  });

  it("checks writes and metadata through follow-up queries", async () => {
    const q = (rows: Record<string, unknown>[]) => async () => rows;
    const insert = byTitle("Inserting");
    expect((await insert.check({ ...ctx([]), query: q([{ _id: "p7", name: "x" }]) })).pass).toBe(
      false,
    );
    expect(
      (
        await insert.check({
          ...ctx([]),
          query: q([{ _id: "p7", name: "Cold brew kit", category: "coffee", price: 25 }]),
        })
      ).pass,
    ).toBe(true);
    expect((await byTitle("Updating").check({ ...ctx([]), query: q([{ stock: 25 }]) })).pass).toBe(
      true,
    );
    expect((await byTitle("Removing").check({ ...ctx([]), query: q([{ _id: "p7" }]) })).pass).toBe(
      false,
    );
    const useIds = byTitle("Addressing");
    expect(
      (
        await useIds.check({
          ...ctx([], "evict", "EVICT FROM products WHERE _id = 'p7'"),
          query: q([]),
        })
      ).pass,
    ).toBe(false);
    expect(
      (
        await useIds.check({
          ...ctx([], "evict", "EVICT FROM products USE IDS 'p7'"),
          query: q([{ _id: "p7" }]),
        })
      ).pass,
    ).toBe(false);
    const idx = [
      {
        _id: "products.idx_products_category_price",
        collection: "products",
        fields: [{ key: ["category"] }],
      },
    ];
    const composite = byTitle("Composite");
    expect((await composite.check({ ...ctx([], "ddl"), query: q(idx) })).pass).toBe(false);
    expect((await composite.check({ ...ctx([{ x: 1 }]), query: q(idx) })).pass).toBe(false);
    expect((await composite.check({ ...ctx(products()), query: q(idx) })).pass).toBe(false);
    expect((await byTitle("Indexes").check({ ...ctx([]), query: q(idx) })).pass).toBe(true);
    expect(
      (await byTitle("Reading query plans").check(ctx([{ plan: "scan" }], "explain"))).pass,
    ).toBe(false);
    expect((await byTitle("Measuring").check(ctx([{ x: 1 }], "profile"))).pass).toBe(false);
  });
});

describe("makeLessonEval", () => {
  it("buffers multi-line input, then submits complete statements in order", async () => {
    const submitted: string[] = [];
    const ev = makeLessonEval({ submit: async (s) => (submitted.push(s), true) });
    const call = (cmd: string) =>
      new Promise<Error | null>((resolve) => ev.eval(cmd, {}, "repl", (err) => resolve(err)));

    expect(await call("SELECT *\n")).toBeInstanceOf(Recoverable);
    // node:repl re-sends the whole accumulation after a Recoverable
    expect(await call("SELECT *\nFROM products;\n")).toBeNull();
    expect(await call("-- just a comment\n")).toBeNull();
    expect(await call("SELECT 1; SELECT 2;\n")).toBeNull();
    await ev.drain();
    expect(submitted).toEqual(["SELECT *\nFROM products", "SELECT 1", "SELECT 2"]);
  });

  it("drops an incomplete tail after complete statements, and reset clears the buffer", async () => {
    const submitted: string[] = [];
    const errors = vi.spyOn(console, "error").mockImplementation(() => {});
    const ev = makeLessonEval({ submit: async (s) => (submitted.push(s), true) });
    const call = (cmd: string) =>
      new Promise<Error | null>((resolve) => ev.eval(cmd, {}, "repl", (err) => resolve(err)));
    await call("SELECT 1; SELECT\n");
    await ev.drain();
    expect(submitted).toEqual(["SELECT 1"]);
    expect(String(errors.mock.calls[0]?.[0])).toContain("discarding incomplete trailing text");
    expect(await call("SELECT *\n")).toBeInstanceOf(Recoverable);
    ev.reset();
    expect(await call("SELECT 2;\n")).toBeNull();
    await ev.drain();
    expect(submitted).toEqual(["SELECT 1", "SELECT 2"]);

    const failing = makeLessonEval({
      submit: async () => {
        throw new Error("kaboom");
      },
    });
    await new Promise((r) => failing.eval("SELECT 1;\n", {}, "repl", r));
    await failing.drain();
    expect(errors.mock.calls.flat().join(" ")).toContain("kaboom");
    errors.mockRestore();
  });
});

describe("tutorial command wiring", () => {
  const deps = {
    detectChannel: () => ({ channel: "npm" as const }),
    now: () => new Date("2026-11-06T12:00:00Z"),
    platform: "linux/x64",
  };
  const run = async (
    args: string[],
    extra: Partial<Parameters<typeof registerTutorialCommand>[1]> = {},
  ) => {
    const program = new Command().exitOverride();
    registerTutorialCommand(program, { ...deps, ...extra });
    process.exitCode = undefined;
    await program.parseAsync(["node", "dittosh", "tutorial", ...args]);
    const code = process.exitCode;
    process.exitCode = undefined;
    return code;
  };

  afterEach(() => vi.restoreAllMocks());

  it("dispatches --interactive with level and data dir", async () => {
    const calls: unknown[] = [];
    const code = await run(["--interactive", "--level", "advanced", "-d", "/tmp/x"], {
      startInteractive: async (o) => {
        calls.push(o);
      },
    });
    expect(code).toBeUndefined();
    expect(calls).toEqual([{ dataDir: "/tmp/x", level: "advanced" }]);
  });

  it("rejects --interactive when unavailable and --level without --interactive", async () => {
    const err = vi.spyOn(console, "error").mockImplementation(() => {});
    expect(await run(["--interactive"])).toBe(1);
    expect(await run(["--level", "beginner"])).toBe(2);
    expect(err.mock.calls.flat().join(" ")).toContain("only apply with --interactive");
  });

  it("writes the Markdown by default", async () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), "tut-cmd-"));
    vi.spyOn(console, "error").mockImplementation(() => {});
    try {
      expect(await run(["-o", path.join(dir, "t.md")])).toBeUndefined();
      expect(fs.existsSync(path.join(dir, "t.md"))).toBe(true);
      expect(await run(["-o", path.join(dir, "t.md")])).toBe(2);
    } finally {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  });
});
