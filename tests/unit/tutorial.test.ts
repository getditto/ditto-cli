describe("writeTutorial", () => {
  let dir: string;
  let errors: string[];
  const deps = {
    detectChannel: () => ({ channel: "npm" as const }),
    now: () => new Date("2026-11-06T12:00:00Z"),
    platform: "linux/x64",
  };

  beforeEach(() => {
    dir = fs.mkdtempSync(path.join(os.tmpdir(), "tut-unit-"));
    errors = [];
    vi.spyOn(console, "error").mockImplementation((m: string) => {
      errors.push(m);
    });
  });
  afterEach(() => {
    vi.restoreAllMocks();
    fs.rmSync(dir, { recursive: true, force: true });
  });

  it("writes a file and refuses to overwrite without force", () => {
    const out = path.join(dir, "t.md");
    expect(writeTutorial({ out }, deps)).toBe(0);
    expect(fs.readFileSync(out, "utf8")).toContain("linux/x64");
    expect(writeTutorial({ out }, deps)).toBe(2);
    expect(errors.join("\n")).toContain("already exists");
    expect(writeTutorial({ out, force: true }, deps)).toBe(0);
  });

  it("reports unwritable targets", () => {
    expect(writeTutorial({ out: path.join(dir, "missing", "t.md") }, deps)).toBe(1);
    expect(errors.join("\n")).toContain("Cannot write");
  });

  it("prints to stdout, and rejects --stdout with --out", () => {
    const write = vi.spyOn(process.stdout, "write").mockImplementation(() => true);
    expect(writeTutorial({ stdout: true }, deps)).toBe(0);
    expect(String(write.mock.calls[0]?.[0])).toContain("# Ditto CLI");
    expect(writeTutorial({ stdout: true, out: "x.md" }, deps)).toBe(2);
  });
});

