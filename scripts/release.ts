/** Tag release tooling. Registry reads are public; mutations run only in publish jobs. */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { pathToFileURL } from "node:url";
import semver from "semver";
import * as tar from "tar";

export const PACKAGE = "@dittolive/cli";
const REGISTRY = "https://registry.npmjs.org";
const REPO = "getditto/ditto-cli";
const out = path.resolve("build/release");
type PackageInfo = {
  name: string;
  version: string;
  gitHead?: string;
  dependencies?: Record<string, string>;
  dist?: { tarball: string; integrity: string };
  [key: string]: unknown;
};

function run(command: string, args: string[], cwd = process.cwd(), env = process.env): string {
  // npm.cmd cannot be execFile'd on Windows; npm-run supplies the JS entry point.
  if (command === "npm" && env.npm_execpath) {
    args = [env.npm_execpath, ...args];
    command = process.execPath;
  }
  return execFileSync(command, args, {
    cwd,
    env,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "inherit"],
  }).trim();
}
function json(file: string): PackageInfo {
  return JSON.parse(fs.readFileSync(file, "utf8"));
}
export function releaseVersion(tag: string): string {
  const version = tag.slice(1);
  if (!tag.startsWith("v") || semver.valid(version) !== version || version.includes("+")) {
    throw new Error(
      "Expected an exact vMAJOR.MINOR.PATCH tag (optional prerelease; no build metadata)",
    );
  }
  return version;
}
export function validateRelease(tag: string, root = process.cwd()): string {
  const version = releaseVersion(tag);
  const pkg = json(path.join(root, "package.json"));
  const lock = JSON.parse(fs.readFileSync(path.join(root, "package-lock.json"), "utf8"));
  if (
    pkg.name !== PACKAGE ||
    pkg.version !== version ||
    lock.version !== version ||
    lock.packages[""].version !== version
  ) {
    throw new Error("Tag, package.json, and package-lock.json versions must match @dittolive/cli");
  }
  const notes = fs.readFileSync(path.join(root, "releases", `${tag}.md`), "utf8");
  if (
    !notes.startsWith(`# dittosh ${tag}\n`) ||
    notes.trim().length < 100 ||
    /\b(TODO|TBD|PLACEHOLDER)\b/.test(notes)
  ) {
    throw new Error(`releases/${tag}.md needs reviewed release notes headed '# dittosh ${tag}'`);
  }
  return version;
}
export function distTag(version: string, latest: string | null): string {
  if (semver.prerelease(version)) return "next";
  return latest && semver.gt(latest, version) ? "previous" : "latest";
}
export function digest(bytes: Buffer, algorithm = "sha256"): string {
  return createHash(algorithm)
    .update(bytes)
    .digest(algorithm === "sha512" ? "base64" : "hex");
}
export function verifyPublished(pkg: PackageInfo, version: string, commit: string): void {
  if (
    pkg.name !== PACKAGE ||
    pkg.version !== version ||
    pkg.gitHead !== commit ||
    !pkg.dist?.integrity?.startsWith("sha512-")
  ) {
    throw new Error(
      "Existing npm version does not belong to this tagged commit; never overwrite or move the tag",
    );
  }
}
export async function registry(version: string, fetchFn = fetch): Promise<PackageInfo | null> {
  const response = await fetchFn(`${REGISTRY}/@dittolive%2fcli/${encodeURIComponent(version)}`, {
    signal: AbortSignal.timeout(30_000),
  });
  if (response.status === 404) return null;
  if (!response.ok) throw new Error(`npm registry lookup failed: HTTP ${response.status}`);
  return (await response.json()) as PackageInfo;
}
function artifact(version: string): string {
  return path.join(out, `dittolive-cli-${version}.tgz`);
}
function output(name: string, value: string): void {
  if (process.env.GITHUB_OUTPUT) fs.appendFileSync(process.env.GITHUB_OUTPUT, `${name}=${value}\n`);
  console.log(`${name}=${value}`);
}

export function formula(
  version: string,
  sha256: string,
  url = `${REGISTRY}/@dittolive/cli/-/cli-${version}.tgz`,
): string {
  releaseVersion(`v${version}`);
  if (!/^[a-f0-9]{64}$/.test(sha256) || !/^https?:\/\/[^"\s\\]+$/.test(url))
    throw new Error("Invalid formula source");
  return `# Generated by getditto/ditto-cli from the tested npm release artifact.
class Dittosh < Formula
  desc "Ditto CLI for offline DQL, sample datasets, and AI agent skills"
  homepage "https://github.com/getditto/ditto-cli"
  url "${url}"
  version "${version}"
  sha256 "${sha256}"
  license "MIT"

  depends_on "node@24"
  on_macos do
    depends_on arch: :arm64
  end

  def install
    system "npm", "install", *std_npm_args
    # The Ditto SDK ships a native binary for every platform (about 380 MB in all).
    # Keep only the one Node loads on this machine (process.platform-arch);
    # if that file isn't there, leave everything as installed.
    target = "#{OS.mac? ? "darwin" : "linux"}-#{Hardware::CPU.arm? ? "arm64" : "x64"}"
    Dir["#{libexec}/lib/node_modules/**/@dittolive/ditto/node"].each do |dir|
      natives = Dir["#{dir}/ditto.*.node"]
      keep = "#{dir}/ditto.#{target}.node"
      next unless natives.include?(keep)

      rm(natives - [keep])
    end
    (bin/"dittosh").write_env_script libexec/"bin/dittosh", PATH: "#{Formula["node@24"].opt_bin}:#{HOMEBREW_PREFIX}/bin:$PATH"
  end

  test do
    ENV["DITTOSH_NO_UPDATE_CHECK"] = "1"
    ENV["DITTOSH_CONFIG_DIR"] = (testpath/"config").to_s
    assert_match version.to_s, shell_output("#{bin}/dittosh --version")
    system bin/"dittosh", "dql", "--data-dir", testpath/"store",
           "INSERT INTO release_smoke DOCUMENTS ({'_id': 'ok', 'answer': 1})"
    assert_match '"answer": 1', shell_output("#{bin}/dittosh dql --data-dir #{testpath}/store 'SELECT answer FROM release_smoke'")
  end
end
`;
}

export async function inspectArchive(file: string, version: string, commit: string): Promise<void> {
  let metadata: PackageInfo | undefined;
  let hasCli = false;
  await tar.t({
    file,
    onReadEntry(entry) {
      if (entry.type !== "File" && entry.type !== "Directory")
        throw new Error("Unexpected link in release archive");
      if (!entry.path.startsWith("package/") || entry.path.split("/").includes(".."))
        throw new Error("Unsafe archive path");
      if (entry.path === "package/dist/cli.js") hasCli = true;
      if (entry.path === "package/package.json") {
        let content = "";
        entry.on("data", (chunk) => {
          content += chunk;
        });
        entry.on("end", () => {
          metadata = JSON.parse(content);
        });
      }
    },
  });
  if (
    !hasCli ||
    metadata?.version !== version ||
    metadata.gitHead !== commit ||
    metadata.name !== PACKAGE
  ) {
    throw new Error("Release archive identity or built CLI is missing");
  }
}

async function buildPackage(version: string, commit: string): Promise<void> {
  fs.mkdirSync(out, { recursive: true });
  const existing = await registry(version);
  if (existing) {
    verifyPublished(existing, version, commit);
    const url = new URL(existing.dist!.tarball);
    if (url.origin !== REGISTRY) throw new Error("Unexpected npm tarball origin");
    const response = await fetch(url, { signal: AbortSignal.timeout(60_000) });
    if (!response.ok) throw new Error(`npm artifact download failed: ${response.status}`);
    const bytes = Buffer.from(await response.arrayBuffer());
    if (`sha512-${digest(bytes, "sha512")}` !== existing.dist!.integrity)
      throw new Error("npm artifact integrity mismatch");
    fs.writeFileSync(artifact(version), bytes);
    console.log("Reusing the immutable npm artifact from this commit for release recovery");
  } else {
    if (!process.env.OFFLINE_TOKEN || !process.env.DATABASE_ID)
      throw new Error("Release needs DQL_OFFLINE_LICENSE and DITTO_DATABASE_ID secrets");
    run(process.execPath, ["--import", "tsx", "scripts/stamp-token.ts"]);
    run("npm", ["run", "build"], process.cwd(), { ...process.env, RELEASE: "true" });
    await packRelease(version, commit, process.env.OFFLINE_TOKEN);
  }
  await inspectArchive(artifact(version), version, commit);
  const checksum = digest(fs.readFileSync(artifact(version)));
  fs.writeFileSync(path.join(out, "dittosh.rb"), formula(version, checksum));
  fs.writeFileSync(
    path.join(out, "SHA256SUMS"),
    `${checksum}  ${path.basename(artifact(version))}\n`,
  );
}

export async function packRelease(version: string, commit: string, token: string): Promise<string> {
  const pkg = json("package.json");
  const lock = JSON.parse(fs.readFileSync("package-lock.json", "utf8"));
  const stage = fs.mkdtempSync(path.join(os.tmpdir(), "dittosh-package-"));
  try {
    fs.cpSync("dist", path.join(stage, "dist"), { recursive: true });
    // Match the SDK version stamped into the bundle and prevent direct dependency drift.
    for (const name of Object.keys(pkg.dependencies ?? {})) {
      pkg.dependencies![name] = lock.packages[`node_modules/${name}`].version;
    }
    delete pkg.devDependencies;
    delete pkg.scripts;
    pkg.gitHead = commit;
    fs.writeFileSync(path.join(stage, "package.json"), `${JSON.stringify(pkg, null, 2)}\n`);
    for (const file of ["README.md", "LICENSE.md"]) fs.copyFileSync(file, path.join(stage, file));
    for (const file of fs.readdirSync(path.join(stage, "dist"))) {
      if (fs.readFileSync(path.join(stage, "dist", file)).includes(Buffer.from(token)))
        throw new Error("Raw offline token found in distribution");
    }
    fs.mkdirSync(out, { recursive: true });
    const packed = JSON.parse(
      run("npm", ["pack", "--ignore-scripts", "--json", "--pack-destination", out], stage),
    );
    if (packed[0].filename !== path.basename(artifact(version)))
      throw new Error("Unexpected npm artifact name");
    return artifact(version);
  } finally {
    fs.rmSync(stage, { recursive: true, force: true });
  }
}

async function publishNpm(version: string, commit: string): Promise<void> {
  await inspectArchive(artifact(version), version, commit);
  const bytes = fs.readFileSync(artifact(version));
  const existing = await registry(version);
  if (existing) {
    verifyPublished(existing, version, commit);
    if (existing.dist!.integrity !== `sha512-${digest(bytes, "sha512")}`)
      throw new Error("Published npm bytes differ from tested artifact");
    console.log("npm version already published with the tested bytes");
    return;
  }
  const channel = distTag(version, (await registry("latest"))?.version ?? null);
  // Same temporary npmrc pattern as the SDK tools publisher. OIDC is the default;
  // a scoped NPM_TOKEN supports first publication before trusted publishing exists.
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), "dittosh-npm-auth-"));
  try {
    const env = { ...process.env };
    if (env.NPM_TOKEN) {
      const config = path.join(temp, ".npmrc");
      fs.writeFileSync(config, `//registry.npmjs.org/:_authToken=${env.NPM_TOKEN}\n`, {
        mode: 0o600,
      });
      env.NPM_CONFIG_USERCONFIG = config;
    }
    run(
      "npm",
      [
        "publish",
        artifact(version),
        "--access",
        "public",
        "--provenance",
        "--tag",
        channel,
        "--registry",
        REGISTRY,
        "--ignore-scripts",
      ],
      process.cwd(),
      env,
    );
    // Registry reads may lag a successful publish briefly. Never build new bytes
    // or attempt a second publish while waiting for the version to appear.
    for (let attempt = 0; attempt < 6; attempt++) {
      const published = await registry(version);
      if (published) {
        verifyPublished(published, version, commit);
        if (published.dist!.integrity !== `sha512-${digest(bytes, "sha512")}`) {
          throw new Error("Registry returned different bytes after publication");
        }
        return;
      }
      await new Promise((resolve) => setTimeout(resolve, 2_000));
    }
    throw new Error("Published npm version is not visible yet; rerun the same tag to recover");
  } finally {
    fs.rmSync(temp, { recursive: true, force: true });
  }
}

async function publishGithub(tag: string, version: string, commit: string): Promise<void> {
  const published = await registry(version);
  if (!published) throw new Error("npm publication must succeed before the GitHub release");
  verifyPublished(published, version, commit);
  if (
    published.dist!.integrity !== `sha512-${digest(fs.readFileSync(artifact(version)), "sha512")}`
  )
    throw new Error("npm bytes differ");
  const latest = (await registry("latest"))?.version === version;
  const releases = JSON.parse(
    run("gh", ["api", `repos/${REPO}/releases?per_page=100`, "--paginate", "--slurp"]),
  ).flat();
  const existing = releases.find((r: { tag_name: string }) => r.tag_name === tag);
  if (existing && !existing.draft) {
    for (const file of [
      artifact(version),
      path.join(out, "SHA256SUMS"),
      path.join(out, "dittosh.rb"),
    ]) {
      const asset = existing.assets.find((a: { name: string }) => a.name === path.basename(file));
      if (!asset || asset.digest !== `sha256:${digest(fs.readFileSync(file))}`) {
        throw new Error(
          "Published GitHub release has missing or different assets; inspect it before retrying",
        );
      }
    }
    console.log("GitHub release already published; leaving its assets unchanged");
    return;
  }
  if (!existing) {
    run("gh", [
      "release",
      "create",
      tag,
      "--repo",
      REPO,
      "--verify-tag",
      "--draft",
      "--title",
      `dittosh ${tag}`,
      "--notes-file",
      `releases/${tag}.md`,
      ...(semver.prerelease(version) ? ["--prerelease"] : []),
    ]);
  }
  run("gh", [
    "release",
    "upload",
    tag,
    "--repo",
    REPO,
    "--clobber",
    artifact(version),
    path.join(out, "SHA256SUMS"),
    path.join(out, "dittosh.rb"),
  ]);
  run("gh", [
    "release",
    "edit",
    tag,
    "--repo",
    REPO,
    "--draft=false",
    `--latest=${latest}`,
    "--notes-file",
    `releases/${tag}.md`,
  ]);
}

async function updateTap(version: string): Promise<void> {
  if (semver.prerelease(version) || (await registry("latest"))?.version !== version) {
    console.log("Skipping Homebrew stable tap for a prerelease or older release");
    return;
  }
  const tap = process.env.HOMEBREW_TAP_REPOSITORY || "getditto/homebrew-tap";
  if (!/^[\w.-]+\/homebrew-[\w.-]+$/.test(tap)) throw new Error("Invalid Homebrew tap repository");
  const repo = JSON.parse(run("gh", ["api", `repos/${tap}`]));
  const branch = repo.default_branch;
  const files = JSON.parse(run("gh", ["api", `repos/${tap}/git/trees/${branch}?recursive=1`]));
  const previous = files.tree.find((f: { path: string }) => f.path === "Formula/dittosh.rb");
  const body = fs.readFileSync(path.join(out, "dittosh.rb"), "utf8");
  if (previous) {
    const blob = JSON.parse(run("gh", ["api", `repos/${tap}/git/blobs/${previous.sha}`]));
    const content = Buffer.from(blob.content, "base64").toString("utf8");
    if (content === body) {
      console.log("Homebrew formula already current");
      return;
    }
    const oldVersion = content.match(/^ {2}version "([^"]+)"$/m)?.[1];
    if (!oldVersion || !semver.valid(oldVersion))
      throw new Error("Cannot determine current Homebrew version");
    if (semver.gte(oldVersion, version))
      throw new Error("Refusing to overwrite or downgrade the existing Homebrew formula");
  }
  const request = {
    message: `Release dittosh v${version}`,
    branch,
    content: Buffer.from(body).toString("base64"),
    ...(previous ? { sha: previous.sha } : {}),
  };
  const input = path.join(out, "tap-update.json");
  fs.writeFileSync(input, JSON.stringify(request));
  run("gh", [
    "api",
    "--method",
    "PUT",
    `repos/${tap}/contents/Formula/dittosh.rb`,
    "--input",
    input,
  ]);
}

export async function main(args = process.argv.slice(2)): Promise<void> {
  const [command, tag = process.env.RELEASE_TAG ?? ""] = args;
  const version = validateRelease(tag);
  const commit = run("git", ["rev-parse", "HEAD"]);
  if (command === "validate") {
    output("version", version);
    output("commit", commit);
    output("prerelease", String(Boolean(semver.prerelease(version))));
  } else if (command === "build") await buildPackage(version, commit);
  else if (command === "npm") await publishNpm(version, commit);
  else if (command === "github") await publishGithub(tag, version, commit);
  else if (command === "homebrew") await updateTap(version);
  else throw new Error("Usage: release.ts validate|build|npm|github|homebrew vX.Y.Z");
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  main().catch((error) => {
    console.error(`release: ${(error as Error).message}`);
    process.exitCode = 1;
  });
}
